"""Convert the approved OBJ to static quads, preserving each vertex's UV and smooth normal."""
import argparse
import hashlib
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
OUTPUT = ROOT / "src/main/java/net/luojiuoscar/isaac_disaster/client/model/familiar/depression/DepressionMesh.java"
TEXTURE = ROOT / "src/main/resources/assets/isaac_disaster/textures/entity/familiar/depression.png"


def generate():
    source = (HERE / "depression.obj").read_bytes()
    positions, uvs, normals, faces = [], [], [], []
    for line in source.decode().splitlines():
        parts = line.split()
        if not parts:
            continue
        if parts[0] == "v":
            positions.append(tuple(map(float, parts[1:])))
        elif parts[0] == "vt":
            uvs.append(tuple(map(float, parts[1:])))
        elif parts[0] == "vn":
            normals.append(tuple(map(float, parts[1:])))
        elif parts[0] == "f":
            faces.append([tuple(int(index) - 1 for index in vertex.split("/")) for vertex in parts[1:]])
    center = [(min(p[axis] for p in positions) + max(p[axis] for p in positions)) / 2 for axis in range(3)]
    rows = []
    for face in faces:
        if len(face) not in (3, 4):
            raise ValueError("Only authored triangles and quads are supported")
        # Minecraft's entity buffer consumes quads; a repeated endpoint preserves a triangle.
        vertices = face if len(face) == 4 else face + [face[-1]]
        values = []
        for position, uv, normal in vertices:
            values.extend(positions[position][axis] - center[axis] for axis in range(3))
            values.extend((uvs[uv][0], 1 - uvs[uv][1]))
            values.extend(normals[normal])
        rows.append("        {" + ", ".join(f"{value:.9f}F" for value in values) + "},")
    java = "\n".join([
        "package net.luojiuoscar.isaac_disaster.client.model.familiar.depression;", "",
        "// Generated by blockbench/familiar/depression/generate_runtime.py.",
        "// OBJ SHA256: " + hashlib.sha256(source).hexdigest(),
        "final class DepressionMesh {",
        "    // Each vertex: centered block coordinates, UV, then its authored smooth normal.",
        "    static final float[][] QUADS = {", *rows, "    };",
        "    private DepressionMesh() {}", "}", "",
    ]).encode()
    return java


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    java, texture = generate(), (HERE / "depression.png").read_bytes()
    if args.check:
        if OUTPUT.read_bytes() != java or TEXTURE.read_bytes() != texture:
            raise SystemExit("Runtime mesh or texture differs from the approved source")
        print("Mesh and texture match the approved source")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        TEXTURE.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_bytes(java)
        TEXTURE.write_bytes(texture)
        print("Generated 136 static quads with per-vertex normals and copied the source texture")
